mark = 0
total_marks = len(question)


def correct_or_wrong(input_answer, answer):
    global mark
    if input_answer == answer:
        print("\n~ Correct...\n")
        mark += 1
    else:
        print("\n~ Wrong...\n")
        mark -= 1


def options(question_id):
    print(question[question_id]["option1"])
    print(question[question_id]["option2"])
    print(question[question_id]["option3"])
    print(question[question_id]["option4"])
    print()

while True:

    for question_id in range(len(question)):
        print(question[question_id]["question"])

        options(question_id)

        input_answer = int(input("Answer: "))
        answer = question[question_id]["answer"]

        correct_or_wrong(input_answer, answer)
    percentage = (mark/total_marks)*100
    print(f"Percent: {percentage}")
    break
